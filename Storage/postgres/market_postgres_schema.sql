-- Tables par schéma (partitions incluses)
SELECT table_schema, table_name
FROM information_schema.tables
WHERE table_schema IN ('orders','payments','inventory','auth')
  AND table_type = 'BASE TABLE'
ORDER BY table_schema, table_name;

-- Isolation : doit renvoyer false pour tous les schémas étrangers
SELECT r.rolname, s.nspname AS schema,
       has_schema_privilege(r.rolname, s.nspname, 'USAGE') AS can_use
FROM (VALUES ('orders_svc'),('payments_svc'),('inventory_svc'),('auth_svc')) AS r(rolname)
CROSS JOIN (VALUES ('orders'),('payments'),('inventory'),('auth')) AS s(nspname)
ORDER BY r.rolname, s.nspname;


