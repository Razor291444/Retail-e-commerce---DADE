-- Création si absent, sinon mise à jour du mot de passe.
-- Création ou mise à jour des rôles SQL
DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN
        SELECT *
        FROM (VALUES
            ('orders_svc',    'Orders_Mdp_2026!'),
            ('payments_svc',  'Payments_Mdp_2026!'),
            ('inventory_svc', 'Inventory_Mdp_2026!'),
            ('auth_svc',      'Auth_Mdp_2026!')
        ) AS roles(rolname, pw)
    LOOP
        IF EXISTS (
            SELECT 1 FROM pg_roles
            WHERE rolname = r.rolname
        ) THEN
            EXECUTE format(
                'ALTER ROLE %I LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE',
                r.rolname, r.pw
            );
        ELSE
            EXECUTE format(
                'CREATE ROLE %I LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE',
                r.rolname, r.pw
            );
        END IF;
    END LOOP;
END
$$;
