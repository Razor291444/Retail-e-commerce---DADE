-- 1. SCHÉMAS
-- =========================================================
CREATE SCHEMA IF NOT EXISTS orders;
CREATE SCHEMA IF NOT EXISTS payments;
CREATE SCHEMA IF NOT EXISTS inventory;
CREATE SCHEMA IF NOT EXISTS auth;


-- =========================================================
-- 2. SCHÉMA ORDERS - SERVICE COMMANDES
-- =========================================================

-- Clients du site (≠ utilisateurs du back-office).
-- auth_user_id : lien logique optionnel vers auth.users (compte mobile du client).
CREATE TABLE IF NOT EXISTS orders.customers (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT        NOT NULL CHECK (length(btrim(name)) > 0),
    email         TEXT        NOT NULL UNIQUE CHECK (email = lower(email)),
    auth_user_id  INTEGER     UNIQUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Table partitionnée par mois sur created_at.
-- Conséquence : la clé primaire doit contenir la clé de partition (id, created_at).
-- Séquence explicite : fiable avec le partitionnement sur toutes les versions.
CREATE SEQUENCE IF NOT EXISTS orders.orders_id_seq;

CREATE TABLE IF NOT EXISTS orders.orders (
    id           BIGINT      NOT NULL DEFAULT nextval('orders.orders_id_seq'),
    customer_id  INTEGER     NOT NULL,
    status       TEXT        NOT NULL DEFAULT 'PENDING'
                 CHECK (status IN ('PENDING','PAID','PREPARING','PAYMENT_FAILED','DELIVERED','CANCELLED')),
    total_cents  INTEGER     NOT NULL CHECK (total_cents >= 0),
    currency     CHAR(3)     NOT NULL DEFAULT 'EUR',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),

    PRIMARY KEY (id, created_at),

    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id)
        REFERENCES orders.customers(id)
        ON DELETE RESTRICT
) PARTITION BY RANGE (created_at);

ALTER SEQUENCE orders.orders_id_seq OWNED BY orders.orders.id;

-- Crée (si absente) la partition du mois contenant p_month.
-- À appeler par un job planifié (pg_cron ou tâche applicative) chaque mois.
CREATE OR REPLACE FUNCTION orders.ensure_month_partition(p_month DATE)
RETURNS TEXT
LANGUAGE plpgsql
AS $$
DECLARE
    v_start DATE := date_trunc('month', p_month)::date;
    v_end   DATE := (date_trunc('month', p_month) + interval '1 month')::date;
    v_name  TEXT := format('orders_%s', to_char(v_start, 'YYYY_MM'));
BEGIN
    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS orders.%I PARTITION OF orders.orders
         FOR VALUES FROM (%L) TO (%L)', v_name, v_start, v_end);
    RETURN v_name;
END
$$;

-- Partition de secours + 6 mois passés + mois courant + 3 mois futurs.
CREATE TABLE IF NOT EXISTS orders.orders_default PARTITION OF orders.orders DEFAULT;

SELECT orders.ensure_month_partition((date_trunc('month', now()) + make_interval(months => m))::date)
FROM generate_series(-6, 3) AS m;

-- Lignes de commande.
-- order_created_at : nécessaire pour la FK composite vers la table partitionnée.
-- product_name : instantané du nom au moment de l'achat (historique stable,
-- et l'écran « mes commandes » ne dépend pas du service Catalogue).
-- product_id : lien LOGIQUE vers MongoDB (catalog.product_id).
CREATE TABLE IF NOT EXISTS orders.order_items (
    id                BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          BIGINT      NOT NULL,
    order_created_at  TIMESTAMPTZ NOT NULL,
    product_id        INTEGER     NOT NULL,
    product_name      TEXT        NOT NULL,
    quantity          INTEGER     NOT NULL CHECK (quantity > 0),
    unit_price_cents  INTEGER     NOT NULL CHECK (unit_price_cents >= 0),

    CONSTRAINT uq_order_items_order_product UNIQUE (order_id, product_id),

    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id, order_created_at)
        REFERENCES orders.orders(id, created_at)
        ON DELETE CASCADE
);

-- Idempotence de POST /v1/orders (en-tête Idempotency-Key).
-- Table séparée : une contrainte UNIQUE sur la table partitionnée
-- devrait inclure created_at et ne garantirait plus rien.
CREATE TABLE IF NOT EXISTS orders.idempotency_keys (
    key              TEXT        PRIMARY KEY,
    request_hash     TEXT        NOT NULL,
    order_id         BIGINT,
    response_status  INTEGER,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Outbox transactionnelle : l'événement est écrit dans la même transaction
-- que la commande, puis publié sur Kafka (volet 4).
CREATE TABLE IF NOT EXISTS orders.outbox (
    id              UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    aggregate_type  TEXT        NOT NULL,
    aggregate_id    TEXT        NOT NULL,
    event_type      TEXT        NOT NULL,
    payload         JSONB       NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at    TIMESTAMPTZ
);

-- Index (créés sur le parent, propagés aux partitions)
CREATE INDEX IF NOT EXISTS idx_orders_customer_created ON orders.orders (customer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_status_created   ON orders.orders (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_order_items_product_id  ON orders.order_items (product_id);
CREATE INDEX IF NOT EXISTS idx_order_items_order       ON orders.order_items (order_id, order_created_at);
CREATE INDEX IF NOT EXISTS idx_orders_outbox_pending   ON orders.outbox (created_at) WHERE published_at IS NULL;

COMMENT ON COLUMN orders.customers.auth_user_id   IS 'Lien logique vers auth.users.id (non contraint)';
COMMENT ON COLUMN orders.order_items.product_id   IS 'Lien logique vers MongoDB catalog.product_id (non contraint)';
COMMENT ON COLUMN orders.order_items.product_name IS 'Instantané du nom du produit à la date de commande';


-- =========================================================
-- 3. SCHÉMA PAYMENTS - SERVICE PAIEMENT
-- =========================================================
CREATE TABLE IF NOT EXISTS payments.payments (
    id               INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT      NOT NULL,
