    id              UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    aggregate_type  TEXT        NOT NULL,
    aggregate_id    TEXT        NOT NULL,
    event_type      TEXT        NOT NULL,
    payload         JSONB       NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at    TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_payments_order_id       ON payments.payments (order_id);
CREATE INDEX IF NOT EXISTS idx_payments_status_created ON payments.payments (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_payments_outbox_pending ON payments.outbox (created_at) WHERE published_at IS NULL;

COMMENT ON COLUMN payments.payments.order_id IS 'Lien logique vers orders.orders.id (non contraint)';


-- =========================================================
-- 4. SCHÉMA INVENTORY - SERVICE STOCK
-- =========================================================
CREATE TABLE IF NOT EXISTS inventory.warehouse (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            TEXT    NOT NULL UNIQUE,
    city            TEXT,
    capacity_units  INTEGER NOT NULL CHECK (capacity_units > 0)
);

-- Un produit peut être stocké dans plusieurs entrepôts.
-- Disponible = quantity - reserved_quantity.
CREATE TABLE IF NOT EXISTS inventory.stock (
    product_id          INTEGER     NOT NULL,
    warehouse_id        INTEGER     NOT NULL,
    quantity            INTEGER     NOT NULL CHECK (quantity >= 0),
    reserved_quantity   INTEGER     NOT NULL DEFAULT 0 CHECK (reserved_quantity >= 0),
    reorder_threshold   INTEGER     NOT NULL DEFAULT 10 CHECK (reorder_threshold >= 0),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    PRIMARY KEY (product_id, warehouse_id),
    CHECK (reserved_quantity <= quantity),

    CONSTRAINT fk_stock_warehouse
        FOREIGN KEY (warehouse_id)
        REFERENCES inventory.warehouse(id)
        ON DELETE RESTRICT
);

-- Réservations du pattern Saga : idempotentes (une par commande et produit),
-- annulables si le paiement échoue, expirables.
CREATE TABLE IF NOT EXISTS inventory.reservations (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT      NOT NULL,
    product_id    INTEGER     NOT NULL,
    warehouse_id  INTEGER     NOT NULL,
    quantity      INTEGER     NOT NULL CHECK (quantity > 0),
    status        TEXT        NOT NULL DEFAULT 'RESERVED'
                  CHECK (status IN ('RESERVED','CONFIRMED','RELEASED','EXPIRED')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at    TIMESTAMPTZ NOT NULL DEFAULT now() + interval '15 minutes',

    CONSTRAINT uq_reservations_order_product UNIQUE (order_id, product_id),

    CONSTRAINT fk_reservations_stock
        FOREIGN KEY (product_id, warehouse_id)
        REFERENCES inventory.stock(product_id, warehouse_id)
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS inventory.outbox (
    id              UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    aggregate_type  TEXT        NOT NULL,
    aggregate_id    TEXT        NOT NULL,
    event_type      TEXT        NOT NULL,
    payload         JSONB       NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at    TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_stock_warehouse_id      ON inventory.stock (warehouse_id);
-- Produits bientôt en rupture (onglet « Vue d'ensemble »)
CREATE INDEX IF NOT EXISTS idx_stock_low
    ON inventory.stock (product_id)
    WHERE quantity - reserved_quantity <= reorder_threshold;
CREATE INDEX IF NOT EXISTS idx_reservations_order      ON inventory.reservations (order_id);
CREATE INDEX IF NOT EXISTS idx_reservations_expiry     ON inventory.reservations (expires_at) WHERE status = 'RESERVED';
CREATE INDEX IF NOT EXISTS idx_inventory_outbox_pending ON inventory.outbox (created_at) WHERE published_at IS NULL;

-- Taux de remplissage par entrepôt (onglet « Logistique »), alerte au-dessus de 90 %.
CREATE OR REPLACE VIEW inventory.v_warehouse_fill AS
SELECT
    w.id                                   AS warehouse_id,
    w.name,
    w.capacity_units,
    COALESCE(SUM(s.quantity), 0)::INTEGER  AS stored_units,
    ROUND(100.0 * COALESCE(SUM(s.quantity), 0) / w.capacity_units, 1) AS fill_rate_pct,
    CASE WHEN COALESCE(SUM(s.quantity), 0) > 0.9 * w.capacity_units
         THEN 'SATURATION' ELSE 'NORMAL' END AS status
FROM inventory.warehouse w
LEFT JOIN inventory.stock s ON s.warehouse_id = w.id
GROUP BY w.id;

COMMENT ON COLUMN inventory.stock.product_id        IS 'Lien logique vers MongoDB catalog.product_id (non contraint)';
COMMENT ON COLUMN inventory.reservations.order_id   IS 'Lien logique vers orders.orders.id (non contraint)';


