-- =========================================================
-- BASE DE DONNÉES MARKET - PostgreSQL 15+
-- Un schéma + un rôle SQL par service. Aucune FK inter-schémas.
--
-- Usage (rejouable, idempotent) :
--   psql -v ON_ERROR_STOP=1 -d market \
--        -v orders_pw="$ORDERS_DB_PASSWORD"       \
--        -v payments_pw="$PAYMENTS_DB_PASSWORD"   \
--        -v inventory_pw="$INVENTORY_DB_PASSWORD" \
--        -v auth_pw="$AUTH_DB_PASSWORD"           \
--        -f market_postgres_schema.sql
--
-- Les mots de passe viennent du .env (jamais dans le dépôt).
-- Les montants sont en centimes (INTEGER), comme dans MongoDB.
-- Les références vers le catalogue (product_id) et entre services
-- (order_id, auth_user_id) sont des liens LOGIQUES vérifiés par le code.
-- =========================================================

SET TIME ZONE 'UTC';

