-- 5. SCHÉMA AUTH - SERVICE AUTHENTIFICATION
-- =========================================================
CREATE TABLE IF NOT EXISTS auth.users (
    id             INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          TEXT        NOT NULL UNIQUE CHECK (email = lower(email)),
    password_hash  TEXT        NOT NULL,          -- argon2 ou bcrypt, jamais en clair
    is_active      BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_login_at  TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS auth.roles (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT    NOT NULL UNIQUE,
    description  TEXT
);

CREATE TABLE IF NOT EXISTS auth.user_roles (
    user_id  INTEGER NOT NULL,
    role_id  INTEGER NOT NULL,

    PRIMARY KEY (user_id, role_id),

    CONSTRAINT fk_user_roles_user
        FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role
        FOREIGN KEY (role_id) REFERENCES auth.roles(id) ON DELETE CASCADE
);

-- Refresh tokens avec rotation : seul le hash est stocké.
CREATE TABLE IF NOT EXISTS auth.refresh_tokens (
    id           UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id      INTEGER     NOT NULL,
    token_hash   TEXT        NOT NULL UNIQUE,
    expires_at   TIMESTAMPTZ NOT NULL,
    revoked_at   TIMESTAMPTZ,
    replaced_by  UUID,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_refresh_tokens_user
        FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_user_roles_role_id        ON auth.user_roles (role_id);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user_id    ON auth.refresh_tokens (user_id);

